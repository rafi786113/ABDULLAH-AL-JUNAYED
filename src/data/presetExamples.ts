import { FullAnalysisResponse, ExplanationLanguage } from '../types/grammar';

export interface PresetItem {
  id: string;
  title: string;
  category: 'قرآن كريم' | 'كلمة دقيقة (صرف عميق)' | 'شعر وحكمة' | 'جملة نحوية مركبة';
  subtleHighlight: string;
  text: string;
  cachedAnalysis?: FullAnalysisResponse;
  cachedAnalysisEn?: FullAnalysisResponse;
  cachedAnalysisBn?: FullAnalysisResponse;
}

export function getPresetAnalysis(
  preset: PresetItem,
  lang: ExplanationLanguage
): FullAnalysisResponse | undefined {
  if (lang === 'bn' && preset.cachedAnalysisBn) return preset.cachedAnalysisBn;
  if (lang === 'en' && preset.cachedAnalysisEn) return preset.cachedAnalysisEn;
  return preset.cachedAnalysis;
}

